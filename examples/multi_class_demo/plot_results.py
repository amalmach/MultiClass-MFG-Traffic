#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Multi-Class Traffic Mean-Field Games — Scientific Visualizations
================================================================

Visualize numerical results generated by the sequential
Newton–GMRES multi-class traffic solver.

Supported models:
    GLWR, GS, GNS

Supported configurations:
    CT, TC, TCT, and general J-class examples.

Figures:
    1. Density evolution
    2. Optimal velocity evolution
    3. Value function evolution
    4. Traffic flux evolution
    5. Density profiles at selected times
    6. Class-wise mass conservation

All figures are saved as PNG files.
"""

import argparse

from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# 1. Directories
# ============================================================

BASE_DIR = Path(__file__).resolve().parent

PLOTS_DIR = BASE_DIR / "plots"


# ============================================================
# 2. Plot settings
# ============================================================

plt.rcParams.update({
    "font.family": "DejaVu Sans",
    "font.size": 10,
    "axes.labelsize": 11,
    "axes.titlesize": 12,
    "figure.dpi": 120,
    "savefig.dpi": 250,
})


# ============================================================
# 3. Command-line arguments
# ============================================================

def parse_arguments():

    parser = argparse.ArgumentParser(
        description=(
            "Visualize multi-class traffic MFG numerical results."
        )
    )

    parser.add_argument(
        "--input",
        type=Path,
        required=True,
        help="Input numerical solution (.npz).",
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=PLOTS_DIR,
        help="Directory for generated figures.",
    )

    parser.add_argument(
        "--show",
        action="store_true",
        help="Display figures interactively.",
    )

    return parser.parse_args()


# ============================================================
# 4. Load numerical results
# ============================================================

def load_results(filename):

    if not filename.is_file():
        raise FileNotFoundError(filename)

    with np.load(filename, allow_pickle=False) as data:

        results = {
            key: np.array(data[key], copy=True)
            for key in data.files
        }

    return results


# ============================================================
# 5. Class labels
# ============================================================

def get_class_labels(J):

    if J == 2:
        return ["Cars", "Trucks"]

    return [
        f"Class {j + 1}"
        for j in range(J)
    ]


# ============================================================
# 6. Save figures
# ============================================================

def save_figure(
    fig,
    filename,
    output_dir,
    show=False,
):

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    destination = output_dir / filename

    fig.savefig(
        destination,
        dpi=250,
        bbox_inches="tight",
    )

    print(f"Saved: {destination}")

    if show:
        plt.show()

    plt.close(fig)


# ============================================================
# 7. Space-time visualizations
# ============================================================

def plot_spacetime(
    variable,
    x,
    t,
    labels,
    title,
    colorbar_label,
    cmap,
    filename,
    output_dir,
    show=False,
):

    J = variable.shape[0]

    fig, axes = plt.subplots(
        J,
        1,
        figsize=(9, 3.3 * J),
        sharex=True,
        squeeze=False,
        constrained_layout=True,
    )

    axes = axes[:, 0]

    # Use a common color scale across vehicle classes.
    vmin = float(np.min(variable))
    vmax = float(np.max(variable))

    for j, ax in enumerate(axes):

        image = ax.pcolormesh(
            t,
            x,
            variable[j],
            shading="nearest",
            cmap=cmap,
            vmin=vmin,
            vmax=vmax,
        )

        ax.set_ylabel("Road position $x$")

        ax.set_title(
            labels[j],
            fontweight="bold",
        )

        fig.colorbar(
            image,
            ax=ax,
            label=colorbar_label,
            pad=0.02,
        )

    axes[-1].set_xlabel("Time $t$")

    fig.suptitle(
        title,
        fontsize=14,
        fontweight="bold",
    )

    save_figure(
        fig,
        filename,
        output_dir,
        show,
    )


# ============================================================
# 8. Density snapshots
# ============================================================

def plot_density_snapshots(
    rho,
    x,
    t,
    labels,
    filename,
    output_dir,
    show=False,
):

    Nt = rho.shape[2] - 1

    indices = [
        0,
        Nt // 2,
        Nt,
    ]

    fig, axes = plt.subplots(
        1,
        3,
        figsize=(15, 4),
        sharey=True,
        constrained_layout=True,
    )

    colors = plt.cm.tab10.colors

    for ax, k in zip(axes, indices):

        for j in range(rho.shape[0]):

            ax.plot(
                x,
                rho[j, :, k],
                marker="o",
                linewidth=1.8,
                markersize=4,
                color=colors[j % len(colors)],
                label=labels[j],
            )

        ax.set_title(
            f"t = {t[k]:.3f}"
        )

        ax.set_xlabel("Road position $x$")

        ax.grid(
            alpha=0.25,
            linestyle="--",
        )

    axes[0].set_ylabel(
        r"Traffic density $\rho_j$"
    )

    axes[-1].legend(
        frameon=False,
    )

    save_figure(
        fig,
        filename,
        output_dir,
        show,
    )


# ============================================================
# 9. Mass conservation
# ============================================================

def plot_mass_conservation(
    rho,
    t,
    dx,
    labels,
    filename,
    output_dir,
    show=False,
):

    J = rho.shape[0]

    mass = dx * np.sum(
        rho,
        axis=1,
    )

    mass_error = (
        mass - mass[:, [0]]
    )

    fig, ax = plt.subplots(
        figsize=(8, 4.5),
        constrained_layout=True,
    )

    for j in range(J):

        ax.plot(
            t,
            mass_error[j],
            marker="o",
            markersize=3,
            label=labels[j],
        )

        print(
            f"{labels[j]}: maximum mass error = "
            f"{np.max(np.abs(mass_error[j])):.3e}"
        )

    ax.set_xlabel("Time $t$")

    ax.set_ylabel(
        r"Mass difference $M_j(t)-M_j(0)$"
    )

    ax.set_title(
        "Class-Wise Mass Conservation"
    )

    ax.grid(alpha=0.3)

    ax.legend(frameon=False)

    save_figure(
        fig,
        filename,
        output_dir,
        show,
    )


# ============================================================
# 10. Main visualization function
# ============================================================

def generate_plots(
    input_file,
    output_dir=PLOTS_DIR,
    show=False,
):

    results = load_results(input_file)

    rho = results["rho"]
    u = results["u"]
    V = results["V"]
    Q = results["Q"]

    x = results["x"]
    t = results["t"]

    J = int(results["J"])
    Nx = int(results["Nx"])
    Nt = int(results["Nt"])

    dx = float(results["dx"])

    model = str(results["model"])

    # Spatial cell centers for cell-based quantities.
    x_centers = (
        x[:-1] + x[1:]
    ) / 2.0

    x_value = x[1:]

    labels = get_class_labels(J)

    # Check array dimensions.
    assert rho.shape == (J, Nx, Nt + 1)
    assert u.shape == (J, Nx, Nt)
    assert V.shape == (J, Nx, Nt + 1)
    assert Q.shape == (J, Nx, Nt)

    assert len(x_centers) == Nx
    assert len(t) == Nt + 1

    # Velocity and flux have Nt temporal values.
    t_velocity = t[:-1]

    prefix = input_file.stem

    print("=" * 65)
    print("MULTI-CLASS TRAFFIC — SCIENTIFIC VISUALIZATIONS")
    print("=" * 65)

    print("Model:", model)
    print("Vehicle classes:", J)
    print("Spatial cells:", Nx)
    print("Temporal steps:", Nt)

    # --------------------------------------------------------
    # Density evolution
    # --------------------------------------------------------

    plot_spacetime(
        variable=rho,
        x=x_centers,
        t=t,
        labels=labels,
        title=f"{model} — Traffic Density Evolution",
        colorbar_label=r"Density $\rho_j$",
        cmap="viridis",
        filename=f"{prefix}_density.png",
        output_dir=output_dir,
        show=show,
    )

    # --------------------------------------------------------
    # Velocity evolution
    # --------------------------------------------------------

    plot_spacetime(
        variable=u,
        x=x_centers,
        t=t_velocity,
        labels=labels,
        title=f"{model} — Optimal Velocity Evolution",
        colorbar_label=r"Velocity $u_j$",
        cmap="plasma",
        filename=f"{prefix}_velocity.png",
        output_dir=output_dir,
        show=show,
    )

    # --------------------------------------------------------
    # Value function evolution
    # --------------------------------------------------------

    plot_spacetime(
        variable=V,
        x=x_value,
        t=t,
        labels=labels,
        title=f"{model} — Value Function Evolution",
        colorbar_label=r"Value function $V_j$",
        cmap="coolwarm",
        filename=f"{prefix}_value.png",
        output_dir=output_dir,
        show=show,
    )

    # --------------------------------------------------------
    # Traffic flux evolution
    # --------------------------------------------------------

    plot_spacetime(
        variable=Q,
        x=x_centers,
        t=t_velocity,
        labels=labels,
        title=f"{model} — Traffic Flux Evolution",
        colorbar_label=r"Flux $Q_j$",
        cmap="magma",
        filename=f"{prefix}_flux.png",
        output_dir=output_dir,
        show=show,
    )

    # --------------------------------------------------------
    # Density snapshots
    # --------------------------------------------------------

    plot_density_snapshots(
        rho=rho,
        x=x_centers,
        t=t,
        labels=labels,
        filename=f"{prefix}_density_snapshots.png",
        output_dir=output_dir,
        show=show,
    )

    # --------------------------------------------------------
    # Mass conservation
    # --------------------------------------------------------

    plot_mass_conservation(
        rho=rho,
        t=t,
        dx=dx,
        labels=labels,
        filename=f"{prefix}_mass_conservation.png",
        output_dir=output_dir,
        show=show,
    )

    print("\n" + "=" * 65)
    print("All six scientific figures generated.")
    print(f"Output directory: {output_dir}")
    print("=" * 65)


# ============================================================
# 11. Entry point
# ============================================================

if __name__ == "__main__":

    args = parse_arguments()

    generate_plots(
        input_file=args.input,
        output_dir=args.output_dir,
        show=args.show,
    )
